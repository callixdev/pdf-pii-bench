"""Regenerate the committed result docs from the baseline results file
(default: results/privacy-filter.json).

Writes RESULTS.md wholesale (do not edit it by hand) and rewrites the
block between the results markers in README.md plus the ground-truth
span counts. Every number in the published prose is computed here, so
the docs cannot drift from the results JSON.

Usage:
    uv run python -m src.publish            # rewrite the files
    uv run python -m src.publish --check    # exit 1 if the files are
                                            # stale (CI)
"""

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

from src.dataset_utils import load_ground_truth

RESULTS_PATH = Path("results/privacy-filter.json")
RESULTS_MD_PATH = Path("RESULTS.md")
README_PATH = Path("README.md")

BEGIN_MARK = "<!-- results:begin (generated by src.publish) -->"
END_MARK = "<!-- results:end -->"

MODE_NOTES = {
    "exact": "prediction must match ground-truth offsets and label exactly",
    "overlap": "same label and (prediction contains ground truth or IoU ≥ 0.5)",
    "redaction": "character-level and label-agnostic: recall is the fraction "
                 "of ground-truth PII characters covered by any prediction "
                 "(a span caught under the wrong label is still redacted), "
                 "precision the fraction of predicted characters inside "
                 "ground truth. Micro only — per-label precision has no "
                 "meaning when matching ignores labels",
}

SCORING_NOTE = (
    "Org/agency contact info is neutral: ground-truth spans whose "
    "subject is an organization or a government agency are excluded "
    "from recall, and predictions covering them are charged no false "
    "positive. The benchmark scores person-linked PII only, matching "
    "the privacy-filter's own label definitions."
)


def _fmt(x):
    return f"{x:.3f}" if x is not None else "–"


def mode_table(mode_results):
    lines = [
        "| Label | P | R | F1 |",
        "|---|---|---|---|",
    ]
    for label in sorted(mode_results.get("per_label", {})):
        scores = mode_results["per_label"][label]
        lines.append(
            f"| `{label}` "
            f"| {_fmt(scores['precision'])} | {_fmt(scores['recall'])} "
            f"| {_fmt(scores['f1'])} |"
        )
    micro = mode_results["micro"]
    lines.append(
        f"| **micro** "
        f"| {_fmt(micro['precision'])} | {_fmt(micro['recall'])} "
        f"| {_fmt(micro['f1'])} |"
    )
    return "\n".join(lines)


def _fmt_date(iso):
    d = date.fromisoformat(iso)
    return f"{d:%B} {d.day}, {d.year}"


def _key_numbers(results):
    """The numbers the prose cites, pulled once from the results."""
    o = results["overlap"]["micro"]
    r = results["redaction"]["micro"]
    e = results["exact"]["micro"]
    return {
        "o": o, "r": r, "e": e,
        "leak": round((1 - r["recall"]) * 100),
    }


def results_markdown(results, n_spans):
    k = _key_numbers(results)
    system = results["system"]
    parts = [
        "<!-- Generated by `uv run python -m src.publish` — do not edit by hand. -->",
        "",
        "# Reference results",
        "",
        f"Evaluation run of {_fmt_date(results['date'])}, on the "
        f"{results['n_documents']}-document dataset ({n_spans:,} "
        "ground-truth spans). The reference system:",
        "",
        f"- **{system}** — `opf.redact()` (OpenAI privacy-filter, default",
        "  Viterbi decoding and operating point) on the canonical text.",
        "  Reproducible from this repo:",
        "  `uv run --extra baseline python -m src.run_privacy_filter`.",
        "",
        "Scores are tied to the dataset revision they were produced",
        "against — ground-truth corrections change the numbers.",
        "",
        f'{SCORING_NOTE} (See `DATASET.md`, "Personal vs. '
        'organizational: the subject tag".)',
    ]
    for mode in ("redaction", "overlap", "exact"):
        parts += [
            "",
            f"## {mode.capitalize()} matching",
            "",
            f"*Criterion: {MODE_NOTES[mode]}.*",
            "",
            mode_table(results[mode]),
        ]
    parts += [
        "",
        "## Reading the results",
        "",
        f"On person-linked PII, {system} reaches "
        f"{k['o']['f1']:.3f} overlap F1 with high precision "
        f"({k['o']['precision']:.3f}) but leaks ~{k['leak']}% of "
        "person-PII characters (redaction char recall "
        f"{k['r']['recall']:.3f}) — the misses are recall on document",
        "structure, not precision.",
    ]
    return "\n".join(parts) + "\n"


def readme_block(results):
    k = _key_numbers(results)
    return f"""{BEGIN_MARK}
| System | Exact F1 | Overlap F1 | Redaction recall |
|---|---|---|---|
| {results['system']} | {k['e']['f1']:.3f} | {k['o']['f1']:.3f} | {k['r']['recall']:.3f} |

The baseline scores {k['e']['f1']:.3f} exact-match F1 and {k['o']['f1']:.3f} overlap F1
with {k['o']['precision']:.3f} overlap precision, but leaks ~{k['leak']}% of
PII characters (redaction recall {k['r']['recall']:.3f}). See `RESULTS.md` for
the full tables and per-label breakdowns.
{END_MARK}"""


def updated_readme(text, results, n_spans):
    if BEGIN_MARK not in text or END_MARK not in text:
        raise SystemExit(
            f"README.md is missing the {BEGIN_MARK} … {END_MARK} markers")
    block = readme_block(results)
    text = re.sub(
        re.escape(BEGIN_MARK) + r".*?" + re.escape(END_MARK),
        lambda _: block, text, count=1, flags=re.S)
    text = re.sub(r"[\d,]+ ground-truth spans",
                  f"{n_spans:,} ground-truth spans", text)
    text = re.sub(r"\| Ground truth \| [\d,]+ char-offset spans \|",
                  f"| Ground truth | {n_spans:,} char-offset spans |", text)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default=RESULTS_PATH)
    parser.add_argument("--results-md", default=RESULTS_MD_PATH,
                        help="RESULTS.md path (override to rehearse)")
    parser.add_argument("--readme", default=README_PATH,
                        help="README.md path (override to rehearse)")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if RESULTS.md or README.md is stale")
    args = parser.parse_args()

    results = json.loads(Path(args.results).read_text())
    if not results.get("date"):
        raise SystemExit("results file has no date — re-run the runner first")
    n_spans = sum(len(v) for v in load_ground_truth().values())

    results_md_path, readme_path = Path(args.results_md), Path(args.readme)
    want = {
        results_md_path: results_markdown(results, n_spans),
        readme_path: updated_readme(
            Path(README_PATH).read_text(), results, n_spans),
    }

    if args.check:
        stale = [str(p) for p, content in want.items()
                 if p.read_text() != content]
        if stale:
            print(f"stale (re-run `uv run python -m src.publish`): "
                  f"{', '.join(stale)}")
            sys.exit(1)
        print("RESULTS.md and README.md are up to date")
        return

    for path, content in want.items():
        path.write_text(content)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
